import io
import json
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import rasterio
from PIL import Image, ImageDraw, ImageFont
from services import __version__
from rasterio.shutil import copy as rio_copy


def write_cog(path: Path, data, grid):
    cube = data[np.newaxis] if data.ndim == 2 else data
    temp = path.with_suffix(".tmp.tif")
    with rasterio.open(
        temp,
        "w",
        driver="GTiff",
        **grid,
        count=len(cube),
        dtype="float32",
        nodata=float("nan"),
        tiled=True,
        compress="deflate",
    ) as dst:
        dst.write(cube.astype("float32"))
        dst.write_mask((np.all(np.isfinite(cube), axis=0) * 255).astype("uint8"))
        dst.update_tags(AREA_OR_POINT="Area", SOFTWARE=f"ARCAMBE GeoAnalytics {__version__}")
    rio_copy(
        temp,
        path,
        driver="COG",
        compress="DEFLATE",
        blocksize=256,
        overview_resampling="NEAREST",
        OVERVIEWS="AUTO",
    )
    temp.unlink()
    # Remove optional external mask generated by platform GDAL versions.
    temp.with_suffix(temp.suffix + ".msk").unlink(missing_ok=True)


def colorize(data, limits=None):
    if data.ndim == 3 and data.shape[0] >= 3:
        channels = []
        valid = np.all(np.isfinite(data[:3]), axis=0)
        for channel_index, band in enumerate(data[:3]):
            values = band[np.isfinite(band)]
            low, high = np.percentile(values, [2, 98]) if values.size else (0, 1)
            if limits:
                low, high = limits[channel_index]
            channels.append(np.nan_to_num(np.clip((band - low) / max(high - low, 1e-6), 0, 1)))
        rgb = np.stack(channels, axis=-1)
    else:
        band = data[0] if data.ndim == 3 else data
        valid = np.isfinite(band)
        values = band[valid]
        low, high = np.percentile(values, [2, 98]) if values.size else (0, 1)
        if limits:
            low, high = limits[0]
        v = np.nan_to_num(np.clip((band - low) / max(high - low, 1e-6), 0, 1))
        stops = np.array([[0.68, 0.34, 0.20], [0.91, 0.83, 0.56], [0.37, 0.69, 0.48], [0.03, 0.32, 0.26]])
        rgb = np.stack([np.interp(v, np.linspace(0, 1, 4), stops[:, c]) for c in range(3)], axis=-1)
    return Image.fromarray(
        np.concatenate([(rgb * 255).astype("uint8"), (valid * 255).astype("uint8")[..., None]], axis=-1),
        "RGBA",
    )


def png_bytes(data, limits=None):
    stream = io.BytesIO()
    colorize(data, limits).save(stream, format="PNG")
    return stream.getvalue()


def map_png(data, provenance, title, locale="en"):
    image = Image.new("RGB", (1200, 960), "#f3f6f5")
    draw = ImageDraw.Draw(image)
    import reportlab

    font_path = Path(reportlab.__file__).parent / "fonts" / "Vera.ttf"

    def text(position, value, fill, font_size):
        draw.text(position, value, fill=fill, font=ImageFont.truetype(str(font_path), font_size))

    pt = locale == "pt"
    text((40, 24), "ARCAMBE GeoAnalytics | " + title, fill="#102f3b", font_size=28)
    if provenance.get("sample"):
        text(
            (40, 66),
            "DADOS SINTÉTICOS DE TESTE" if pt else "SYNTHETIC TEST DATA",
            fill="#995b18",
            font_size=20,
        )
    raster = colorize(data)
    factor = min(1040 / raster.width, 650 / raster.height)
    raster = raster.resize(
        (round(raster.width * factor), round(raster.height * factor)), Image.Resampling.NEAREST
    )
    left, top = (1200 - raster.width) // 2, 108
    image.paste(raster, (left, top), raster)
    text((1125, 118), "N", fill="#0b3a42", font_size=20)
    draw.polygon([(1133, 150), (1127, 170), (1139, 170)], fill="#0b3a42")
    # Projected UTM metric scale bar, using actual image scaling.
    m_per_px = provenance["resolution_m"] * data.shape[-1] / raster.width
    metres = max(10, round(raster.width * m_per_px / 4 / 10) * 10)
    px = metres / m_per_px
    draw.line((left, 790, left + px, 790), fill="#102f3b", width=5)
    text((left, 800), f"{metres} m", fill="#102f3b", font_size=18)
    first = data[0] if data.ndim == 3 else data
    values = first[np.isfinite(first)]
    if values.size and data.ndim == 2:
        low, high = np.percentile(values, [2, 98])
        for step in range(250):
            v = step / 249
            stops = np.array([[173, 87, 51], [232, 212, 143], [94, 176, 122], [8, 82, 66]])
            col = tuple(int(np.interp(v, np.linspace(0, 1, 4), stops[:, c])) for c in range(3))
            draw.line((850 + step, 790, 850 + step, 810), fill=col)
        text((850, 816), f"{low:.3f} - {high:.3f} | 2-98%", fill="#102f3b", font_size=16)
    elif data.ndim == 3:
        text(
            (750, 790),
            "RGB: canais 1-3 / percentis 2-98" if pt else "RGB: channels 1-3 / percentiles 2-98",
            fill="#102f3b",
            font_size=16,
        )
    lines = [
        f"{provenance['crs']} | {provenance['resolution_m']} m | {provenance.get('acquired_at', '')}",
        ("Limites" if pt else "Bounds") + ": " + ", ".join(f"{v:.2f}" for v in provenance["bounds"]),
        f"{provenance.get('scene_id', '')} | {provenance.get('license', '')}",
        datetime.now(timezone.utc).isoformat(),
    ]
    for i, line in enumerate(lines):
        text((40, 852 + i * 23), line[:135], fill="#3b555e", font_size=15)
    return image


def export_products(directory, data, grid, provenance, title):
    directory.mkdir(parents=True, exist_ok=True)
    write_cog(directory / "result.tif", data, grid)
    (directory / "provenance.json").write_text(
        json.dumps(provenance, ensure_ascii=False, indent=2, allow_nan=False), encoding="utf-8"
    )
    colorize(data).save(directory / "preview.png")
    for locale in ("en", "pt"):
        image = map_png(data, provenance, title, locale)
        image.save(directory / f"map-{locale}.png")
        # The report is a raster map page; georeferenced data is in the separate COG.
        from reportlab.lib.utils import ImageReader
        from reportlab.pdfgen.canvas import Canvas

        canvas = Canvas(str(directory / f"map-{locale}.pdf"), pagesize=(900, 720))
        canvas.setTitle("ARCAMBE GeoAnalytics | " + title)
        canvas.drawImage(ImageReader(image), 0, 0, width=900, height=720)
        canvas.save()
    return [
        ("cog", "result.tif", "image/tiff"),
        ("json", "provenance.json", "application/json"),
        ("preview", "preview.png", "image/png"),
        *[
            (
                f"{fmt}-{locale}",
                f"map-{locale}.{fmt}",
                f"{'image/png' if fmt == 'png' else 'application/pdf'}",
            )
            for locale in ("en", "pt")
            for fmt in ("png", "pdf")
        ],
    ]
